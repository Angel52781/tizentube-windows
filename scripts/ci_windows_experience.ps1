# Windows-hosted YouTube E2E. Executes only on isolated GitHub runner.
# No developer/owner desktop connection and no account credentials.
param(
    [Parameter(Mandatory=$true)][string]$Executable,
    [string]$EvidenceDirectory = 'windows-experience-evidence'
)
$ErrorActionPreference = 'Stop'
$exe = (Resolve-Path $Executable).Path
New-Item -ItemType Directory -Force $EvidenceDirectory | Out-Null
$dir = (Resolve-Path $EvidenceDirectory).Path
$url = 'https://www.youtube.com/watch?v=dQw4w9WgXcQ'
$checks = [ordered]@{}

function Assert-E2E([bool]$condition, [string]$reason) {
    if (-not $condition) { throw "EXPERIENCE_E2E_FAILED: $reason" }
    $script:checks[$reason] = 'PASS'
    Write-Host "[PASS] $reason"
}
function Read-Json([string]$name) {
    $file = Join-Path $dir $name
    Assert-E2E (Test-Path $file) "artifact:$name"
    return (Get-Content $file -Raw -Encoding utf8 | ConvertFrom-Json)
}
function Invoke-Host([string]$label, [string[]]$additional, [int]$duration) {
    $capture = Join-Path $dir "$label-telemetry.json"
    $arguments = @('--smoke-test',"$duration",'--url',$url,'--telemetry-file',$capture) + $additional
    $started = Start-Process -FilePath $exe -WorkingDirectory (Split-Path $exe) -ArgumentList $arguments -Wait -PassThru
    Assert-E2E ($started.ExitCode -eq 0) "host-exit:$label"
    if (Test-Path $capture) {
        $telemetry = Get-Content $capture -Raw -Encoding utf8 | ConvertFrom-Json
        Assert-E2E ($telemetry.summary.modsInitializedCount -ge 1) "bundled-mods:$label"
    }
}

try {
    Write-Host 'Running guest-only Windows WebView2 PiP video E2E...'
    Invoke-Host 'floating' @('--floating-visual-probe') 53
    $before = Read-Json 'floating-before.json'
    $clicked = Read-Json 'floating-button-click.json'
    $after = Read-Json 'floating-after.json'
    Assert-E2E ($clicked -eq $true) 'actual-player-button-click'
    Assert-E2E ($before.videoReadyState -ge 2 -and $before.videoWidth -gt 0) 'original-video-playing'
    Assert-E2E ($after.active -eq $true -and $after.playerInBody -eq $true) 'same-player-moved-to-floating-window'
    Assert-E2E ($after.videoRect.width -gt 150 -and $after.videoRect.height -gt 100) 'visible-floating-video-geometry'
    Assert-E2E ($after.currentTime -gt $before.currentTime) 'video-time-continues-while-floating'

    # The preview is generated by WebView2, not a screenshot of the runner's
    # potentially locked desktop. Check actual image pixels, not just PNG size.
    $capture = Join-Path $dir 'floating-preview.png'
    Assert-E2E (Test-Path $capture) 'webview2-video-frame-captured'
    Add-Type -AssemblyName System.Drawing
    $bitmap = [System.Drawing.Bitmap]::FromFile($capture)
    try {
        Assert-E2E ($bitmap.Width -gt 150 -and $bitmap.Height -gt 100) 'preview-image-dimensions'
        $unique = New-Object 'System.Collections.Generic.HashSet[int]'
        $bright = 0
        $sampled = 0
        for ($y = [int]($bitmap.Height * .18); $y -lt [int]($bitmap.Height * .78); $y += 5) {
            for ($x = [int]($bitmap.Width * .18); $x -lt [int]($bitmap.Width * .82); $x += 5) {
                $color = $bitmap.GetPixel($x, $y)
                $luma = [int](.2126 * $color.R + .7152 * $color.G + .0722 * $color.B)
                [void]$unique.Add(([int]($color.R / 8) * 1024) + ([int]($color.G / 8) * 32) + [int]($color.B / 8))
                if ($luma -gt 40) { $bright++ }
                $sampled++
            }
        }
        Assert-E2E ($sampled -gt 100 -and $bright -gt ($sampled * .1) -and $unique.Count -gt 35) 'real-nonblack-video-pixels'
        "pixels=$sampled bright=$bright colors=$($unique.Count)" | Set-Content (Join-Path $dir 'video-frame-pixel-metrics.txt')
    } finally { $bitmap.Dispose() }

    Write-Host 'Running separate-process cinema preference E2E...'
    Invoke-Host 'theater-user-choice' @('--theater-user-probe') 34
    $userChoice = Read-Json 'theater-after-click.json'
    $savedFile = Join-Path $env:LOCALAPPDATA 'TizenTube\theater-preference.json'
    Assert-E2E (Test-Path $savedFile) 'theater-preference-saved-on-windows-disk'
    $saved = (Get-Content $savedFile -Raw).Trim()
    Assert-E2E ($saved -in @('true','false')) 'theater-preference-valid-boolean'
    Assert-E2E ($userChoice.theaterPreference.ToString().ToLowerInvariant() -eq $saved) 'trusted-user-click-saved'
    Invoke-Host 'theater-restart' @('--theater-restore-probe') 42
    $restart = Read-Json 'theater-after-restart.json'
    $settled = Read-Json 'theater-after-settle.json'
    Assert-E2E ($settled.theaterPreference.ToString().ToLowerInvariant() -eq $saved) 'theater-disk-choice-survives-restart'
    Assert-E2E ($settled.theater.ToString().ToLowerInvariant() -eq $saved) 'theater-layout-survives-restart'
    Assert-E2E (!$settled.fullscreen -and !$settled.youtubeFullscreen) 'theater-never-activates-fullscreen'
    Assert-E2E ($settled.videoRect.width -gt 300 -and $settled.videoRect.height -gt 170) 'theater-restoration-keeps-video-visible'
    Assert-E2E ($settled.pipButtonVisible -and $settled.pipButtonBetweenCaptionsAndSettings) 'floating-control-exactly-between-cc-and-settings'
    Assert-E2E ($settled.currentTime -gt $restart.currentTime) 'playback-continues-after-cinema-restore'

    # Exercise the real settings modal -> IPC -> Windows disk pipeline across
    # independent exe launches. Windows runner reboot isn't necessary: a new
    # process proves settings survived beyond process-local JS/session memory.
    Write-Host 'Checking persisted settings and YouTube masthead Back control...'
    Invoke-Host 'preferences-first-launch' @('--preferences-setup-probe') 30
    $setup = Read-Json 'preferences-setup.json'
    Assert-E2E ($setup -eq $true) 'settings-ui-save-dispatched'
    $prefsFile = Join-Path $env:LOCALAPPDATA 'TizenTube\UserData\user_preferences.json'
    Assert-E2E (Test-Path $prefsFile) 'settings-saved-to-native-windows-profile'
    $nativePrefs = (Get-Content $prefsFile -Raw -Encoding utf8 | ConvertFrom-Json)
    Assert-E2E ($nativePrefs.payload.ui.highContrast -eq $true -and
        $nativePrefs.payload.sponsorblock.autoSkip -eq $false -and
        $nativePrefs.payload.playback.defaultSpeed -eq 1.5) 'native-disk-preserves-last-settings-choice'
    Invoke-Host 'preferences-independent-restart' @('--preferences-restart-probe') 30
    $restored = Read-Json 'preferences-restart.json'
    Assert-E2E ($restored.hostPrefsPresent -and $restored.highContrast -and
        $restored.autoSkip -eq $false -and $restored.defaultSpeed -eq 1.5) 'full-preferences-restored-in-new-windows-process'

    Invoke-Host 'navigation-back' @('--navigation-back-probe') 30
    $back = Read-Json 'navigation-back.json'
    Assert-E2E ($back.request.found -and
        $back.request.pushed -eq '/results' -and
        ($back.result.current -eq $back.request.original -or
         $back.nativeSource -eq $back.request.original) -and
        ($null -eq $back.result -or $back.result.buttonExists)) 'actual-youtube-masthead-back-navigates-spa-history'

    # HiDPI font rendering & comment layout probe verification
    Write-Host 'Verifying HiDPI layout, font rendering, and comment styles...'
    $layout = Read-Json 'hidpi-layout-probe.json'
    Assert-E2E ($layout.stylesInjected -eq $true) 'hidpi-ui-styles-injected'
    Assert-E2E ($layout.devicePixelRatio -ge 1) 'hidpi-device-pixel-ratio-valid'
    Assert-E2E ($layout.pipBetweenCaptionsAndSettings -eq $true) 'pip-controls-aligned-between-cc-and-settings'

    # AdBlock, SponsorBlock, and DeArrow feature verification on hosted Windows runner
    Write-Host 'Verifying AdBlock, SponsorBlock, and DeArrow features on hosted Windows runner...'
    $features = Read-Json 'features-probe.json'
    Assert-E2E ($features.adblock.loaded -eq $true) 'adblock-module-loaded'
    Assert-E2E ($features.adblock.enabled -eq $true) 'adblock-enabled-by-default'
    Assert-E2E ($features.adblock.stylesheetInjected -eq $true) 'adblock-cosmetic-stylesheet-injected'
    Assert-E2E ($features.sponsorblock.loaded -eq $true) 'sponsorblock-module-loaded'
    Assert-E2E ($features.sponsorblock.enabled -eq $true) 'sponsorblock-enabled-by-default'
    Assert-E2E ($features.sponsorblock.autoSkip -eq $true) 'sponsorblock-autoskip-enabled'
    Assert-E2E ($features.sponsorblock.categoriesConfigured -eq $true) 'sponsorblock-categories-configured'
    Assert-E2E ($features.dearrow.loaded -eq $true) 'dearrow-module-loaded'
    Assert-E2E ($features.dearrow.enabled -eq $true) 'dearrow-enabled-by-default'

    # Process-tree CPU and private RAM metrics collection & validation
    Write-Host 'Collecting and verifying process-tree CPU and private RAM metrics...'
    $telemetryScenarios = @('floating', 'theater-user-choice', 'theater-restart')
    $allProcesses = [ordered]@{}
    $totalPeakWsMb = 0.0
    $totalPeakPrivMb = 0.0
    $totalCpuTimeMs = 0.0

    foreach ($sc in $telemetryScenarios) {
        $tFileName = "$sc-telemetry.json"
        $tData = Read-Json $tFileName
        Assert-E2E ($tData.summary.totalPrivateMemoryBytes -gt 0) "process-tree-private-ram-positive:$sc"
        Assert-E2E ($tData.summary.totalWorkingSetBytes -gt 0) "process-tree-working-set-positive:$sc"
        Assert-E2E ($tData.processes.Count -ge 1) "process-tree-processes-enumerated:$sc"

        if ($tData.summary.totalWorkingSetMb -gt $totalPeakWsMb) {
            $totalPeakWsMb = [double]$tData.summary.totalWorkingSetMb
        }
        if ($tData.summary.totalPrivateMemoryMb -gt $totalPeakPrivMb) {
            $totalPeakPrivMb = [double]$tData.summary.totalPrivateMemoryMb
        }

        foreach ($p in $tData.processes) {
            $pidKey = $p.pid.ToString()
            if (-not $allProcesses.Contains($pidKey)) {
                $allProcesses[$pidKey] = [ordered]@{
                    pid = $p.pid
                    name = $p.name
                    role = $p.role
                    peakWorkingSetMb = [double]$p.workingSetMb
                    peakPrivateMemoryMb = [double]$p.privateMemoryMb
                    cpuTimeMs = [double]$p.cpuTimeMs
                }
            } else {
                if ([double]$p.workingSetMb -gt $allProcesses[$pidKey].peakWorkingSetMb) {
                    $allProcesses[$pidKey].peakWorkingSetMb = [double]$p.workingSetMb
                }
                if ([double]$p.privateMemoryMb -gt $allProcesses[$pidKey].peakPrivateMemoryMb) {
                    $allProcesses[$pidKey].peakPrivateMemoryMb = [double]$p.privateMemoryMb
                }
                if ([double]$p.cpuTimeMs -gt $allProcesses[$pidKey].cpuTimeMs) {
                    $allProcesses[$pidKey].cpuTimeMs = [double]$p.cpuTimeMs
                }
            }
            $totalCpuTimeMs += [double]$p.cpuTimeMs
        }
    }

    $perfMetrics = [ordered]@{
        timestamp = [DateTime]::UtcNow.ToString('o')
        environment = 'github-actions-windows-latest'
        scenarios = $telemetryScenarios
        summary = [ordered]@{
            peakWorkingSetMb = [Math]::Round($totalPeakWsMb, 2)
            peakPrivateMemoryMb = [Math]::Round($totalPeakPrivMb, 2)
            trackedProcessCount = $allProcesses.Count
            totalCpuTimeMs = [Math]::Round($totalCpuTimeMs, 1)
        }
        processes = @($allProcesses.Values)
    }

    $perfMetricsJsonPath = Join-Path $dir 'process-tree-performance-metrics.json'
    $perfMetrics | ConvertTo-Json -Depth 6 | Set-Content $perfMetricsJsonPath -Encoding utf8
    Assert-E2E (Test-Path $perfMetricsJsonPath) 'artifact:process-tree-performance-metrics.json'

    $summaryLines = @(
        "==================================================",
        "  TizenTube Windows - Process Performance Summary",
        "==================================================",
        "Environment:          github-actions-windows-latest",
        "Timestamp:            $($perfMetrics.timestamp)",
        "Peak Working Set:     $($perfMetrics.summary.peakWorkingSetMb) MB",
        "Peak Private Memory:  $($perfMetrics.summary.peakPrivateMemoryMb) MB",
        "Tracked Processes:    $($perfMetrics.summary.trackedProcessCount)",
        "Total CPU Time:       $($perfMetrics.summary.totalCpuTimeMs) ms",
        "--------------------------------------------------",
        "Processes:"
    )
    foreach ($proc in $allProcesses.Values) {
        $summaryLines += "  PID $($proc.pid) [$($proc.role)] $($proc.name): Private=$($proc.peakPrivateMemoryMb)MB, WS=$($proc.peakWorkingSetMb)MB, CPU=$($proc.cpuTimeMs)ms"
    }
    $summaryLines += "=================================================="
    $summaryTxtPath = Join-Path $dir 'process-tree-performance-summary.txt'
    $summaryLines | Set-Content $summaryTxtPath -Encoding utf8
    Assert-E2E (Test-Path $summaryTxtPath) 'artifact:process-tree-performance-summary.txt'

    Assert-E2E ($perfMetrics.summary.peakPrivateMemoryMb -gt 0) 'performance-private-ram-metric-positive'
    Assert-E2E ($perfMetrics.summary.peakWorkingSetMb -gt 0) 'performance-working-set-metric-positive'
    Assert-E2E ($perfMetrics.summary.trackedProcessCount -ge 1) 'performance-process-tree-metrics-collected'
    Assert-E2E ($perfMetrics.summary.totalCpuTimeMs -ge 0) 'performance-total-cpu-time-tracked'

    $success = [ordered]@{ status = 'PASS'; source = $env:GITHUB_SHA; runner = $env:RUNNER_OS; checks = $checks }
    $success | ConvertTo-Json -Depth 6 | Set-Content (Join-Path $dir 'results.json') -Encoding utf8
    Write-Host "Windows guest-only experience E2E PASS: $($checks.Count) checks"
} catch {
    $failure = [ordered]@{status='FAIL'; error=$_.Exception.Message; source=$env:GITHUB_SHA; runner=$env:RUNNER_OS; checks=$checks}
    $failure | ConvertTo-Json -Depth 6 | Set-Content (Join-Path $dir 'results.json') -Encoding utf8
    Write-Error $_.Exception.Message
    exit 1
}
