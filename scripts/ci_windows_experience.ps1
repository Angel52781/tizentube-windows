# Windows-hosted YouTube E2E. Executes only on isolated GitHub runner.
# No developer/owner desktop connection and no account credentials.
param(
    [Parameter(Mandatory=$true)][string]$Executable,
    [string]$EvidenceDirectory = 'windows-experience-evidence'
)
$ErrorActionPreference = 'Stop'
$exe = (Resolve-Path $Executable).Path
New-Item -ItemType Directory -Force $EvidenceDirectory | Out-Null
$dir = (Resolve-Path $EvidenceDirectory).Path
$url = 'https://www.youtube.com/watch?v=dQw4w9WgXcQ'
$checks = [ordered]@{}

function Assert-E2E([bool]$condition, [string]$reason) {
    if (-not $condition) { throw "EXPERIENCE_E2E_FAILED: $reason" }
    $script:checks[$reason] = 'PASS'
    Write-Host "[PASS] $reason"
}
function Read-Json([string]$name) {
    $file = Join-Path $dir $name
    Assert-E2E (Test-Path $file) "artifact:$name"
    return (Get-Content $file -Raw -Encoding utf8 | ConvertFrom-Json)
}
function Invoke-Host([string]$label, [string[]]$additional, [int]$duration) {
    $capture = Join-Path $dir "$label-telemetry.json"
    $arguments = @('--smoke-test',"$duration",'--url',$url,'--telemetry-file',$capture) + $additional
    $started = Start-Process -FilePath $exe -WorkingDirectory (Split-Path $exe) -ArgumentList $arguments -Wait -PassThru
    Assert-E2E ($started.ExitCode -eq 0) "host-exit:$label"
    if (Test-Path $capture) {
        $telemetry = Get-Content $capture -Raw -Encoding utf8 | ConvertFrom-Json
        Assert-E2E ($telemetry.summary.modsInitializedCount -ge 1) "bundled-mods:$label"
    }
}

try {
    Write-Host 'Running guest-only Windows WebView2 PiP video E2E...'
    Invoke-Host 'floating' @('--floating-visual-probe') 53
    $before = Read-Json 'floating-before.json'
    $clicked = Read-Json 'floating-button-click.json'
    $after = Read-Json 'floating-after.json'
    Assert-E2E ($clicked -eq $true) 'actual-player-button-click'
    Assert-E2E ($before.videoReadyState -ge 2 -and $before.videoWidth -gt 0) 'original-video-playing'
    Assert-E2E ($after.active -eq $true -and $after.playerInBody -eq $true) 'same-player-moved-to-floating-window'
    Assert-E2E ($after.videoRect.width -gt 150 -and $after.videoRect.height -gt 100) 'visible-floating-video-geometry'
    Assert-E2E ($after.currentTime -gt $before.currentTime) 'video-time-continues-while-floating'

    # The preview is generated by WebView2, not a screenshot of the runner's
    # potentially locked desktop. Check actual image pixels, not just PNG size.
    $capture = Join-Path $dir 'floating-preview.png'
    Assert-E2E (Test-Path $capture) 'webview2-video-frame-captured'
    Add-Type -AssemblyName System.Drawing
    $bitmap = [System.Drawing.Bitmap]::FromFile($capture)
    try {
        Assert-E2E ($bitmap.Width -gt 150 -and $bitmap.Height -gt 100) 'preview-image-dimensions'
        $unique = New-Object 'System.Collections.Generic.HashSet[int]'
        $bright = 0
        $sampled = 0
        for ($y = [int]($bitmap.Height * .18); $y -lt [int]($bitmap.Height * .78); $y += 5) {
            for ($x = [int]($bitmap.Width * .18); $x -lt [int]($bitmap.Width * .82); $x += 5) {
                $color = $bitmap.GetPixel($x, $y)
                $luma = [int](.2126 * $color.R + .7152 * $color.G + .0722 * $color.B)
                [void]$unique.Add(([int]($color.R / 8) * 1024) + ([int]($color.G / 8) * 32) + [int]($color.B / 8))
                if ($luma -gt 40) { $bright++ }
                $sampled++
            }
        }
        Assert-E2E ($sampled -gt 100 -and $bright -gt ($sampled * .1) -and $unique.Count -gt 35) 'real-nonblack-video-pixels'
        "pixels=$sampled bright=$bright colors=$($unique.Count)" | Set-Content (Join-Path $dir 'video-frame-pixel-metrics.txt')
    } finally { $bitmap.Dispose() }

    Write-Host 'Running separate-process cinema preference E2E...'
    Invoke-Host 'theater-user-choice' @('--theater-user-probe') 34
    $userChoice = Read-Json 'theater-after-click.json'
    $savedFile = Join-Path $env:LOCALAPPDATA 'TizenTube\theater-preference.json'
    Assert-E2E (Test-Path $savedFile) 'theater-preference-saved-on-windows-disk'
    $saved = (Get-Content $savedFile -Raw).Trim()
    Assert-E2E ($saved -in @('true','false')) 'theater-preference-valid-boolean'
    Assert-E2E ($userChoice.theaterPreference.ToString().ToLowerInvariant() -eq $saved) 'trusted-user-click-saved'
    Invoke-Host 'theater-restart' @('--theater-restore-probe') 42
    $restart = Read-Json 'theater-after-restart.json'
    $settled = Read-Json 'theater-after-settle.json'
    Assert-E2E ($settled.theaterPreference.ToString().ToLowerInvariant() -eq $saved) 'theater-disk-choice-survives-restart'
    Assert-E2E ($settled.theater.ToString().ToLowerInvariant() -eq $saved) 'theater-layout-survives-restart'
    Assert-E2E (!$settled.fullscreen -and !$settled.youtubeFullscreen) 'theater-never-activates-fullscreen'
    Assert-E2E ($settled.videoRect.width -gt 300 -and $settled.videoRect.height -gt 170) 'theater-restoration-keeps-video-visible'
    Assert-E2E ($settled.pipButtonVisible -and $settled.pipButtonBetweenCaptionsAndSettings) 'floating-control-exactly-between-cc-and-settings'
    Assert-E2E ($settled.currentTime -gt $restart.currentTime) 'playback-continues-after-cinema-restore'

    $success = [ordered]@{ status = 'PASS'; source = $env:GITHUB_SHA; runner = $env:RUNNER_OS; checks = $checks }
    $success | ConvertTo-Json -Depth 6 | Set-Content (Join-Path $dir 'results.json') -Encoding utf8
    Write-Host "Windows guest-only experience E2E PASS: $($checks.Count) checks"
} catch {
    $failure = [ordered]@{status='FAIL'; error=$_.Exception.Message; source=$env:GITHUB_SHA; runner=$env:RUNNER_OS; checks=$checks}
    $failure | ConvertTo-Json -Depth 6 | Set-Content (Join-Path $dir 'results.json') -Encoding utf8
    Write-Error $_.Exception.Message
    exit 1
}
